"""Original dateutil normalized() plus independent CPython round observations."""
from pathlib import Path
import argparse,hashlib,json,math,random,struct,sys
import generate_relative_delta_reference as base
from generate_auto_date_reference import moon,formatted
ROOT=base.ROOT
FLOAT_SHA='d558f168de7ec864b64ffad7ee2b056bda4efca1ee68ca690189354b893ccc76'


def fields(delta):
    result={key:getattr(delta,key) for key in ['years','months',*base.RELATIVE,*base.ABSOLUTE]}
    result['weekday']=None if delta.weekday is None else [delta.weekday.weekday,delta.weekday.n]
    return result


def generate(source):
    if sys.version_info[:3]!=(3,12,14):raise ValueError('requires fixed CPython3.12.14')
    if hashlib.sha256((ROOT/'.moonagent/upstream/cpython-v3.12.14/Objects/floatobject.c').read_bytes()).hexdigest()!=FLOAT_SHA:raise ValueError('float source differs')
    ref=base.load_reference(source);constructor=ref['relativedelta'];original,_=base.generate(source)
    options=[row['options'] for row in original['cases']]
    randomizer=random.Random(2026102302)
    for _ in range(160):
        options.append({key:randomizer.randrange(-10000000,10000000)*10.**randomizer.randrange(-12,3) for key in ['days','hours','minutes','seconds','microseconds']})
    options += [{'day':31,'leapdays':2.25,'on_weekday':[0,0],'days':1.5,'hours':-37.25},
                {'microseconds':-0.5},{'microseconds':0.5},{'microseconds':1.5},{'microseconds':-1.5}]
    code='// Generated by original dateutil normalized(); decimal round uses original CPython.\n';rows=[]
    for index,opts in enumerate(options):
        kwargs=opts.copy()
        if 'on_weekday' in kwargs:
            day,nth=kwargs.pop('on_weekday');kwargs['weekday']=ref['weekday'](day,nth)
        original_delta=constructor(**kwargs);delta=original_delta.normalized();attrs=fields(delta)
        code+='\n///|\ntest '+moon('relative delta original normalized '+str(index))+' {\n  let value = @date.RelativeDelta::new('+base.arguments(opts)+')\n  let delta = value.normalized()\n'
        code+='  assert_eq(delta.years(), '+str(delta.years)+'L)\n  assert_eq(delta.months(), '+str(delta.months)+')\n'
        code+='  assert_eq(['+', '.join('delta.'+key+'()' for key in base.RELATIVE)+'], '+moon([float(attrs[key]) for key in base.RELATIVE])+')\n'
        code+='  assert_eq(['+', '.join('delta.'+key+'()' for key in base.ABSOLUTE)+'], ['+', '.join('None' if attrs[key] is None else 'Some('+str(attrs[key])+')' for key in base.ABSOLUTE)+'])\n'
        if delta.weekday is None:code+='  assert_true(delta.weekday() is None)\n'
        else:
            code+='  assert_eq(delta.weekday().unwrap().weekday(), '+str(delta.weekday.weekday)+')\n'
            code+='  assert_eq(delta.weekday().unwrap().nth(), '+('None' if delta.weekday.n is None else 'Some('+str(delta.weekday.n)+')')+')\n'
        # Normalization does not mutate the original even when zero/invalid
        # absolute fields or a fractional leapdays value are retained.
        code+='  assert_eq(value.days(), '+moon(float(original_delta.days))+')\n}\n'
        rows.append(dict(options=opts,expected=attrs))
    scalar='// Generated original CPython decimal-round binary64 observations.\n';groups=[]
    for digits in [0,8,10,11]:
        values=[0.,-0.,math.ulp(0.),-math.ulp(0.),sys.float_info.max,-sys.float_info.max,0.5,-0.5]
        for _ in range(200):
            pivot=(randomizer.randrange(-100000,100000)+0.5)*10.**(-digits)
            values.extend([pivot,math.nextafter(pivot,-math.inf),math.nextafter(pivot,math.inf)])
        for _ in range(250):
            bits=randomizer.getrandbits(64);value=struct.unpack('>d',bits.to_bytes(8,'big'))[0]
            if math.isfinite(value):values.append(value)
        entries=[];scalar+='\n///|\ntest '+moon('relative exact decimal round '+str(digits))+' {\n  let cases = [\n'
        for value in values:
            expected=round(value,digits);bits=int.from_bytes(struct.pack('>d',expected),'big')
            entries.append([value,bits]);scalar+='    ('+moon(value)+', '+str(bits)+'UL),\n'
        scalar+='  ]\n  for (value, expected) in cases {\n    assert_eq(relative_decimal_round(value, '+str(digits)+').reinterpret_as_uint64(), expected)\n  }\n}\n'
        groups.append(dict(digits=digits,entries=entries))
    payload=dict(source_sha256=base.REL_SHA,float_source_sha256=FLOAT_SHA,python='3.12.14',normalized=rows,decimal_round=groups)
    return payload,formatted(code),formatted(scalar)


def main():
    parser=argparse.ArgumentParser();parser.add_argument('source',type=Path);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    payload,code,scalar=generate(args.source)
    files={ROOT/'testdata/relative_normalize_reference.json':json.dumps(payload,indent=2)+'\n',ROOT/'ticker/date/relative_normalize_reference_test.mbt':code,ROOT/'ticker/date/relative_round_reference_wbtest.mbt':scalar}
    for path,text in files.items():
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit('reference differs: '+str(path))
        else:path.write_text(text)
    print('relative normalized:',len(payload['normalized']),'named; exact decimal:',sum(len(g['entries']) for g in payload['decimal_round']),'binary64 observations in 4 groups')

if __name__=='__main__':main()
