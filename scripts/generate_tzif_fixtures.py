"""Generate test-only Bytes literals from compiled IANA 2026e zoneinfo.

Usage: python3 scripts/generate_tzif_fixtures.py ZONEINFO_DIRECTORY
The compiler command and pinned data archive hash are in testdata/tzif/README.md.
"""
from pathlib import Path
import hashlib
import sys
import json
import struct

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
zones = {'new_york': 'America/New_York', 'paris': 'Europe/Paris',
         'lord_howe': 'Australia/Lord_Howe', 'nuuk': 'America/Nuuk'}
manifest = {}
literals = {}
for key, name in zones.items():
    data = (source / name).read_bytes()
    (root / 'testdata/tzif' / (key + '.tzif')).write_bytes(data)
    manifest[key] = {'zone': name, 'release': '2026e', 'sha256': hashlib.sha256(data).hexdigest()}
    chunks = ['b"' + ''.join('\\x%02x' % x for x in data[i:i+64]) + '"' for i in range(0, len(data), 64)]
    literals[key] = '///|\nlet tzif_' + key + ' : Bytes =\n  ' + ' +\n  '.join(chunks) + '\n'
def synthetic(offset, transitions=(), leap=False, footer=b'', initial_name=b'LMT'):
    # A minimal v2 file: compatibility block, then authoritative 64-bit block.
    def block(width, entries, include_leap):
        names = initial_name + b'\0'
        header = b'TZif2' + bytes(15) + struct.pack('>6I', 0, 0, int(include_leap), len(entries), 2, len(names))
        fmt = '>q' if width == 8 else '>i'
        body = b''.join(struct.pack(fmt, at) for at, _ in entries) + bytes(kind for _, kind in entries)
        body += struct.pack('>iBB', offset, 0, 0) + struct.pack('>iBB', 3600, 0, 0) + names
        if include_leap:
            body += struct.pack(fmt, 78796800) + struct.pack('>i', 1)
        return header + body
    return block(4, [], False) + block(8, transitions, leap) + b'\n' + footer + b'\n'

extra = {
    'fixed': synthetic(561),
    'leap': synthetic(0, leap=True),
    'outsize_offset': synthetic(86400),
    'rule_only': synthetic(0, footer=b'EST5EDT,M3.2.0,M11.1.0'),
    'outside_calendar': synthetic(0, transitions=[(-9223372036854775808, 1), (253402300900, 0)]),
}
for key, data in extra.items():
    literals[key] = '///|\nlet tzif_' + key + ' : Bytes = b"' + ''.join('\\x%02x' % x for x in data) + '"\n'
for package, keys in [('ticker/date', [*zones, *extra]), ('scene', ['new_york', 'paris']), ('pyplot', ['new_york'])]:
    text = '// Generated by scripts/generate_tzif_fixtures.py; IANA 2026e, public domain.\n'
    (root / package / 'tzif_fixture_test.mbt').write_text(text + '\n'.join(literals[key] for key in keys))
(root / 'testdata/tzif/manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
