"""Build the optional production IANA catalogue from pinned official archives.

Usage: python3 scripts/generate_tzdb.py ARCHIVE_DIRECTORY [--check]
ARCHIVE_DIRECTORY must contain tzdata2026e.tar.gz and tzcode2026e.tar.gz.
No network, system zoneinfo or system zic is used. --check verifies generated
files without changing the checkout. Requires Python 3.9+, make, C and moonfmt.
"""
from pathlib import Path
import argparse
import datetime as dt
import hashlib
import io
import json
import subprocess
import tarfile
import tempfile
import zoneinfo

ROOT = Path(__file__).resolve().parents[1]
RELEASE = '2026e'
ARCHIVES = {
    'tzdata2026e.tar.gz': 'b26882805f26aac59d5b222978e6580484b834ccdc98be89df2f05a6dc53a652',
    'tzcode2026e.tar.gz': 'cc3d27ca2a0d8399504551b920970d80af83bfb9c216e8082a15491921935d54',
}
SOURCES = ('africa', 'antarctica', 'asia', 'australasia', 'europe',
           'northamerica', 'southamerica', 'etcetera', 'factory', 'backward')
PROBES = ((1800, 1, 2), (1900, 1, 2), (1970, 1, 2), (2000, 7, 1),
          (2024, 3, 10), (2024, 7, 1), (2026, 10, 30), (2026, 11, 1),
          (2027, 1, 2), (2040, 1, 2), (2040, 7, 1), (2400, 1, 2),
          (2400, 7, 1), (9999, 7, 1))
HEADER = '// Generated by scripts/generate_tzdb.py from IANA 2026e; public domain.\n'


def run(command, **kwargs):
    return subprocess.run([str(x) for x in command], check=True,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          **kwargs).stdout


def formatted(source):
    return run(['moonfmt', '-'], input=source.encode()).decode()


def quoted(value):
    return json.dumps(value, ensure_ascii=True)


def generate(archive_dir, work):
    for name, digest in ARCHIVES.items():
        data = (archive_dir / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError('pinned archive checksum mismatch: ' + name)
        with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as archive:
            for member in archive.getmembers():
                path = Path(member.name)
                if path.is_absolute() or '..' in path.parts or member.issym() or member.islnk():
                    raise ValueError('unexpected archive entry: ' + member.name)
            archive.extractall(work)
    if (work / 'version').read_text().strip() != RELEASE:
        raise ValueError('unexpected source release')
    run(['make', '-C', work, 'zic'])
    compiler = run([work / 'zic', '--version']).decode().strip()
    if compiler != 'zic (tzcode) ' + RELEASE:
        raise ValueError('unexpected compiler: ' + compiler)
    output = work / 'zoneinfo'
    run([work / 'zic', '-b', 'slim', '-d', output, *(work / x for x in SOURCES)])
    zones, links = set(), {}
    for source in SOURCES:
        for line in (work / source).read_text().splitlines():
            fields = line.split('#', 1)[0].split()
            if fields and fields[0] == 'Zone':
                zones.add(fields[1])
            elif fields and fields[0] == 'Link':
                target, name = fields[1:3]
                if name in links and links[name] != target:
                    raise ValueError('conflicting alias: ' + name)
                links[name] = target
    names = sorted(zones | links.keys())
    actual = sorted(str(p.relative_to(output)) for p in output.rglob('*') if p.is_file())
    if actual != names:
        raise ValueError('compiled names do not match all source Zone/Link declarations')

    def canonical(name):
        seen = set()
        while name in links:
            if name in seen:
                raise ValueError('alias cycle: ' + name)
            seen.add(name)
            name = links[name]
        if name not in zones:
            raise ValueError('unresolved alias: ' + name)
        return name

    blobs, indices, entries, manifest, goldens = [], {}, [], {}, []
    instants = [dt.datetime(*fields, tzinfo=dt.timezone.utc) for fields in PROBES]
    epoch = dt.datetime(1970, 1, 1, tzinfo=dt.timezone.utc)
    seconds = [int((instant - epoch).total_seconds()) for instant in instants]
    for name in names:
        data = (output / name).read_bytes()
        if data[4] not in (ord('2'), ord('3')):
            raise ValueError('unexpected TZif version: ' + name)
        if data not in indices:
            indices[data] = len(blobs)
            blobs.append(data)
        index = indices[data]
        entries.append((name, index))
        reference = zoneinfo.ZoneInfo.from_file(io.BytesIO(data))
        offsets = [int(instant.astimezone(reference).utcoffset().total_seconds())
                   for instant in instants]
        goldens.append((name, offsets))
        manifest[name] = {'canonical': canonical(name), 'blob': index,
                          'sha256': hashlib.sha256(data).hexdigest(), 'bytes': len(data)}
        if data != (output / canonical(name)).read_bytes():
            raise ValueError('alias has different compiled data: ' + name)
    blob_source = HEADER + '\n///|\nlet embedded_zones : Array[Bytes] = [\n'
    for data in blobs:
        blob_source += '  b"' + ''.join('\\x%02x' % x for x in data) + '",\n'
    blob_source += ']\n'
    index_source = HEADER + '\n///|\nlet data_version = ' + quoted(RELEASE) + '\n'
    index_source += '\n///|\nlet zone_entries : Array[(String, Int)] = [\n'
    index_source += ''.join('  (' + quoted(name) + ', ' + str(index) + '),\n' for name, index in entries)
    index_source += ']\n'
    golden_source = HEADER + '\n///|\nlet reference_instants : Array[Double] = [\n'
    golden_source += ''.join('  ' + str(second) + 'L.to_double() / 86400.0,\n' for second in seconds)
    golden_source += ']\n\n///|\nlet reference_offsets : Array[(String, Array[Int])] = [\n'
    golden_source += ''.join('  (' + quoted(name) + ', [' + ', '.join(map(str, offsets)) + ']),\n'
                             for name, offsets in goldens)
    golden_source += ']\n\n///|\nlet reference_aliases : Array[(String, String)] = [\n'
    golden_source += ''.join('  (' + quoted(name) + ', ' + quoted(canonical(name)) + '),\n'
                             for name in sorted(links))
    golden_source += ']\n'
    metadata = {'release': RELEASE, 'compiler': compiler, 'zic_flags': ['-b', 'slim'],
                'sources': list(SOURCES), 'archive_sha256': ARCHIVES,
                'name_count': len(names), 'zone_count': len(zones), 'alias_count': len(links),
                'unique_blob_count': len(blobs), 'unique_tzif_bytes': sum(map(len, blobs)),
                'probe_utc_dates': [x.isoformat() for x in instants], 'names': manifest}
    outputs = {
        ROOT / 'ticker/date/tzdb/data.mbt': formatted(blob_source),
        ROOT / 'ticker/date/tzdb/index.mbt': formatted(index_source),
        ROOT / 'ticker/date/tzdb/reference_test.mbt': formatted(golden_source),
        ROOT / 'ticker/date/tzdb/manifest.json': json.dumps(metadata, indent=2) + '\n',
        ROOT / 'ticker/date/tzdb/LICENSE': (work / 'LICENSE').read_text(),
    }
    return outputs, metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive_directory', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='mathplotlib-tzdb-') as directory:
        outputs, metadata = generate(args.archive_directory.resolve(), Path(directory))
    for path, expected in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit('generated file differs: ' + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    print(('Verified' if args.check else 'Generated') + ' IANA ' + RELEASE + ': ' +
          str(metadata['name_count']) + ' names, ' + str(metadata['unique_blob_count']) +
          ' unique blobs, ' + str(metadata['unique_tzif_bytes']) + ' bytes')


if __name__ == '__main__':
    main()
