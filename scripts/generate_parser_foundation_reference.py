"""Execute pinned dateutil lexer/YMD classes as private parser groundwork oracles."""
from pathlib import Path
import argparse
import ast
import calendar
import hashlib
import io
import itertools
import json
import re
import sys
import six
from generate_auto_date_reference import moon, formatted

ROOT=Path(__file__).resolve().parents[1]
PARSER_SHA='ee494377289c92c401fd7825fb7500981c33098a2bd40219aa4948713e9d1fff'
TEST_SHA='95b9f01f8d2f4091fea049f90f9ebc05991ccf0c3455144d50778a888ceeefb0'


def option(value):return 'None' if value is None else 'Some('+str(value)+')'

def expected_tuple(value):return '('+', '.join(option(x) for x in value)+')'


def generate(source):
    if hashlib.sha256(source.read_bytes()).hexdigest()!=PARSER_SHA:raise ValueError('parser source differs')
    tests=source.parents[3]/'tests/test_parser.py'
    if hashlib.sha256(tests.read_bytes()).hexdigest()!=TEST_SHA:raise ValueError('parser tests differ')
    namespace=dict(re=re,StringIO=io.StringIO,six=six,integer_types=(int,),text_type=str,monthrange=calendar.monthrange)
    nodes=[n for n in ast.parse(source.read_text()).body if isinstance(n,ast.ClassDef) and n.name in ['_timelex','_ymd']]
    exec(compile(ast.Module(body=nodes,type_ignores=[]),str(source),'exec'),namespace)
    tables={}
    import datetime
    for node in ast.parse(tests.read_text()).body:
        if isinstance(node,ast.Assign) and len(node.targets)==1 and isinstance(node.targets[0],ast.Name) and node.targets[0].id in ['PARSER_TEST_CASES','PARSER_DEFAULT_TEST_CASES']:
            tables[node.targets[0].id]=eval(compile(ast.Expression(node.value),str(tests),'eval'),dict(datetime=datetime.datetime))
    inputs=[row[0] for rows in tables.values() for row in rows]
    inputs+=['', '\x00\x00August 29, 1924', '20\x0003-09-25', 'Sep.20.2009', 'a..12...b',
             '12,34', '1,2', '12,', '12.34.56', '12.a', '12..a', '.5h', '12,,34',
             '１２:３４:５６', '٢٠٢٤-٠٢-٢٩', '²³-01-2003', '𝟚𝟘𝟚𝟜.𝟘𝟚.𝟚𝟡',
             'Сентябрь.20.2009', 'Jan\u00a0２０２４', '\u2003Thu\tSep\n25\r2003', '\u001cSep\u001f2003',
             'A\u0301.2024', 'Sep💫20', '🇨🇳.20', '1e3', 'NaN', 'inf']
    inputs=list(dict.fromkeys(inputs))
    code='// Generated by executing pinned dateutil2.9.0.post0 _timelex/_ymd.\n'
    lex_rows=[]
    for index,value in enumerate(inputs):
        tokens=namespace['_timelex'].split(value)
        code+='\n///|\ntest '+moon('parser lexer reference '+str(index))+' {\n  assert_eq(parser_lex('+moon(value)+'), '+moon(tokens)+')\n}\n'
        lex_rows.append(dict(text=value,tokens=tokens))
    ymd_rows=[]
    for yearfirst,dayfirst in itertools.product([False,True],repeat=2):
        for count in range(4):
            rows=[]
            for values in itertools.product([1,12,13,31,32,100,101,2000],repeat=count):
                ymd=namespace['_ymd']()
                try:
                    for value in values:ymd.append(value)
                    expected=ymd.resolve_ymd(yearfirst,dayfirst)
                except ValueError:expected=None
                rows.append((values,expected))
                ymd_rows.append(dict(values=values,yearfirst=yearfirst,dayfirst=dayfirst,result=expected))
            code+='\n///|\ntest '+moon('parser numeric YMD reference %s/%s/%s'%(yearfirst,dayfirst,count))+' {\n'
            code+='  let cases : Array[(Array[Int32], (Int32?, Int32?, Int32?)?)] = [\n'
            for values,expected in rows:
                code+='    ('+moon(list(values))+', '+('None' if expected is None else 'Some('+expected_tuple(expected)+')')+'),\n'
            code+='  ]\n  for (values, expected) in cases {\n    let result = try {\n      let ymd = parser_ymd()\n      for value in values { ymd.append_number(value) }\n      Some(ymd.resolve(yearfirst='+moon(yearfirst)+', dayfirst='+moon(dayfirst)+'))\n    } catch { _ => None }\n    assert_eq((values, result), (values, expected))\n  }\n}\n'
    tagged=[]
    sequences=[[],[('1',None)],[('12',None)],[('32',None)],[('100',None)],[('0001',None)],[('0099',None)],
               [('١٢',None)],[('２０２４',None)],[('²',None)], [('1900','Y'),('2','M')], [('2000','Y'),('2','M')],
               [('2','M')],[('1','D')],[('2','M'),('29','D')], [('2','M'),('1','M')], [('2000',None),('2024',None)],
               [('Jan',None)], [('1',None),('2',None),('3',None),('4',None)]]
    for order in itertools.permutations([('2003','Y'),('9','M'),('25','D')]):sequences.append(list(order))
    for order in itertools.permutations([('25',None),('9','M'),('03',None)]):sequences.append(list(order))
    for order in itertools.permutations([('2003','Y'),('9','M'),('25',None)]):sequences.append(list(order))
    for index,entries in enumerate(sequences):
        ymd=namespace['_ymd']()
        try:
            for text,label in entries:ymd.append(text,label)
            result=ymd.resolve_ymd(False,False)
            expected='Some(('+expected_tuple(result)+', '+moon(ymd.century_specified)+'))'
            result_data=[result,ymd.century_specified]
        except (ValueError,AssertionError):expected='None';result_data=None
        code+='\n///|\ntest '+moon('parser tagged YMD reference '+str(index))+' {\n  let result = try {\n    let ymd = parser_ymd()\n'
        for text,label in entries:code+='    ymd.append_text('+moon(text)+(', label='+label if label else '')+')\n'
        code+='    Some((ymd.resolve(), ymd.century))\n  } catch { _ => None }\n  assert_eq(result, '+expected+')\n}\n'
        tagged.append(dict(entries=entries,result=result_data))
    day_rows=[]
    for index,entries in enumerate([[],[(2,'M')],[(1900,'Y'),(2,'M')],[(2000,'Y'),(2,'M')],[(2024,'Y'),(2,'M'),(29,'D')]]):
        ymd=namespace['_ymd']()
        for value,label in entries:ymd.append(value,label)
        values=[-1,0,1,28,29,30,31,32]
        expected=[ymd.could_be_day(value) for value in values]
        code+='\n///|\ntest '+moon('parser day feasibility reference '+str(index))+' {\n  let ymd = parser_ymd()\n'
        for value,label in entries:code+='  ymd.append_number('+str(value)+', label='+label+')\n'
        code+='  assert_eq('+moon(values)+'.map(value => ymd.could_be_day(value)), '+moon(expected)+')\n}\n'
        day_rows.append(dict(entries=entries,values=values,expected=expected))
    manifest=dict(dateutil_version='2.9.0.post0',parser_sha256=PARSER_SHA,test_parser_sha256=TEST_SHA,python=sys.version.split()[0],
                  lexer_cases=lex_rows,ymd_cases=ymd_rows,tagged_cases=tagged,day_cases=day_rows,
                  named_case_count=len(lex_rows)+16+len(tagged)+len(day_rows),
                  note='Private foundations only. Full datestr2num, field construction, timezone and runtime clock are not verified by this suite.')
    return {ROOT/'ticker/date/parser_foundation_reference_wbtest.mbt':formatted(code),ROOT/'testdata/parser_foundation_reference.json':json.dumps(manifest,ensure_ascii=False,indent=2)+'\n'}


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('parser_py',type=Path);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,content in generate(args.parser_py).items():
        if args.check:
            if path.read_text()!=content:raise SystemExit('reference differs: '+str(path.relative_to(ROOT)))
        else:path.write_text(content)
    print(('Verified' if args.check else 'Generated')+' parser foundations')


if __name__=='__main__':main()
