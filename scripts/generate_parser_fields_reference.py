"""Execute original dateutil default _parse and Decimal field operations."""
from pathlib import Path
import argparse,ast,calendar,datetime,decimal,hashlib,io,itertools,json,re,string,sys,time,warnings
import six
from generate_auto_date_reference import moon,formatted
from generate_parser_foundation_reference import PARSER_SHA,TEST_SHA,ROOT,option

FIELDS=['year','month','day','weekday','hour','minute','second','microsecond','tzname','tzoffset']


def opt(value):return 'None' if value is None else 'Some('+moon(value)+')'


def generate(source):
    if hashlib.sha256(source.read_bytes()).hexdigest()!=PARSER_SHA:raise ValueError('parser source differs')
    tests=source.parents[3]/'tests/test_parser.py'
    if hashlib.sha256(tests.read_bytes()).hexdigest()!=TEST_SHA:raise ValueError('parser test source differs')
    ns=dict(re=re,string=string,time=time,warnings=warnings,warn=warnings.warn,StringIO=io.StringIO,six=six,integer_types=(int,),text_type=str,
            monthrange=calendar.monthrange,Decimal=decimal.Decimal,datetime=datetime)
    names=['_timelex','_resultbase','parserinfo','_ymd','parser']
    nodes=[n for n in ast.parse(source.read_text()).body if isinstance(n,ast.ClassDef) and n.name in names]
    exec(compile(ast.Module(body=nodes,type_ignores=[]),str(source),'exec'),ns)
    parser=ns['parser']();parser.info._year=2026;parser.info._century=2000
    inputs=[]
    for node in ast.parse(tests.read_text()).body:
        if isinstance(node,ast.Assign) and len(node.targets)==1 and isinstance(node.targets[0],ast.Name) and node.targets[0].id in ['PARSER_TEST_CASES','PARSER_DEFAULT_TEST_CASES']:
            rows=eval(compile(ast.Expression(node.value),str(tests),'eval'),dict(datetime=datetime.datetime));inputs.extend(row[0] for row in rows)
    inputs+=['', ' ', 'ad', 'AM', '25 PM', '0 am', '12 am', '13 PM', '13pm', '23 pm',
             'Jan of 01','Jan of 76','Jan of 77','Jan of 25','Feb 31','2000-00-01','2024-01-32',
             '２０２４-０２-２９ １３:０５:２９,１２３４５６７', '٢٠٢٤-٠٢-٢٩ ١٣:٠٥', '² Jan 2024',
             '2024-01-01 10:00 UTC', '2024-01-01 10:00 GMT', '2024-01-01 10:00 z',
             '2024-01-01 10:00 BRST', '2024-01-01 10:00 GMT+3', '2024-01-01 10:00 BRST-3',
             '2024-01-01 10:00 -0300 (BRST)', '2024-01-01 10:00 +00:99', '2024-01-01 10:00 +24:00',
             '2024-01-01 10:00 NAN','2024-01-01 10:00 INF','2024-01-01 10:00 UTC+00',
             '2024-01-01 10:00:60', '99h', '1: test', 'NaN', '2024-01-01 12:30:45.1234567890123456789',
             '2000-01', '0001-01', '24-12-31', '76-01-01', '77-01-01', 'Jan 77', 'Jan 76']
    for value in ['4.2','5.6','0.29','1.00000000000000000000000000001','0.'+'9'*27,'0.'+'9'*28,'0.'+'9'*29,
                  '0.'+'0'*50+'1','5.5999999999999999999999999999','5.6000000000000000000000000001','100.1','23.99999999999999999999999999999']:
        for suffix in ['h','m','s']:inputs.append(value+suffix)
    inputs=list(dict.fromkeys(inputs))
    code='// Generated by original default parser._parse with a fixed 2026 year pivot.\n'
    rows=[]
    for index,text in enumerate(inputs):
        result,_=parser._parse(text)
        expected=None if result is None else [getattr(result,field) for field in FIELDS]+[result.century_specified,result.ampm]
        code+='\n///|\ntest '+moon('parser field reference '+str(index))+' {\n  let result = try {\n    let fields = parser_select('+moon(text)+', 2026)\n'
        code+='    Some(('+', '.join('fields.'+field for field in FIELDS)+', fields.century, fields.ampm))\n  } catch { _ => None }\n'
        code+='  assert_eq(result, '+('None' if expected is None else 'Some(('+', '.join(opt(value) for value in expected[:10])+', '+moon(expected[10])+', '+opt(expected[11])+'))')+')\n}\n'
        rows.append(dict(text=text,fields=expected))
    manifest=dict(dateutil_version='2.9.0.post0',parser_sha256=PARSER_SHA,test_parser_sha256=TEST_SHA,python=sys.version.split()[0],
                  reference_year=2026,decimal_precision=decimal.getcontext().prec,field_names=FIELDS+['century','ampm'],cases=rows,named_case_count=len(rows),
                  note='Raw _parse fields, including invalid calendar values; default filling, DateTime validation, timezone construction and numeric epoch conversion remain separate acceptance requirements.')
    return {ROOT/'ticker/date/parser_fields_reference_wbtest.mbt':formatted(code),ROOT/'testdata/parser_fields_reference.json':json.dumps(manifest,ensure_ascii=False,indent=2)+'\n'}


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('parser_py',type=Path);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,value in generate(args.parser_py).items():
        if args.check:
            if path.read_text()!=value:raise SystemExit('reference differs: '+str(path.relative_to(ROOT)))
        else:path.write_text(value)
    print(('Verified' if args.check else 'Generated')+' parser field references')


if __name__=='__main__':main()
